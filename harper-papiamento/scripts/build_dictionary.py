#!/usr/bin/env python3
"""Generate harper-papiamento/dictionary.dict from the official vocabulary.

Source: "Anexo: Vocabulario di Papiamento" of the Landsverordening schrijfwijze
Papiamento, Afkondigingsblad van Aruba 2018 no. 68 (data/vocabulario_ab_2018_68.csv),
plus data/supplement.txt.

Harper's lexer produces one token per word, splitting on spaces, hyphens and
periods, so multi-word entries ("a pesar di"), hyphenated entries ("ex-casa")
and abbreviations ("p.e.") are split into the parts the lexer will see.
The full multi-word and hyphenated forms are still used by the orthography
rules in src/rules/.

Usage (from the repository root):
    python3 harper-papiamento/scripts/build_dictionary.py
"""

import csv
import re
import unicodedata
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
VOCAB = CRATE / "data" / "vocabulario_ab_2018_68.csv"
SUPPLEMENT = CRATE / "data" / "supplement.txt"
OUT = CRATE / "dictionary.dict"


def normalize(word: str) -> str:
    word = unicodedata.normalize("NFC", word.strip())
    return word.replace("’", "'").replace("‘", "'")


def tokens(entry: str):
    """Split an entry into the word tokens Harper's lexer will produce."""
    for part in re.split(r"[\s\-/.]+", entry):
        part = part.strip("'")
        if len(part) >= 2 or part.isalpha():
            yield part


def sort_key(word: str):
    base = unicodedata.normalize("NFD", word.casefold())
    return ("".join(c for c in base if not unicodedata.combining(c)), word)


def main():
    words = set()

    with VOCAB.open(encoding="utf-8") as f:
        for row in csv.DictReader(f):
            words.update(tokens(normalize(row["word"])))

    for line in SUPPLEMENT.read_text(encoding="utf-8").splitlines():
        entry = line.split("#", 1)[0].strip()
        if entry:
            words.add(normalize(entry))

    # A word that only appears capitalized inside a proper name ("San Nicolas")
    # is kept capitalized; Harper's lookups are case-insensitive anyway.
    lower = {w.lower() for w in words if w == w.lower()}
    words = {w for w in words if w == w.lower() or w.lower() not in lower}

    ordered = sorted(words, key=sort_key)
    header = [
        str(len(ordered)),
        "# Papiamento (Aruba) word list for Harper.",
        "# Generated by scripts/build_dictionary.py from the 'Anexo: Vocabulario di",
        "# Papiamento' of the Landsverordening schrijfwijze Papiamento",
        "# (Afkondigingsblad van Aruba 2018 no. 68). Do not edit by hand.",
        "",
    ]
    OUT.write_text("\n".join(header + ordered) + "\n", encoding="utf-8")
    print(f"wrote {len(ordered)} words to {OUT.relative_to(CRATE.parent)}")


if __name__ == "__main__":
    main()
